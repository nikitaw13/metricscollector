package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"log"
	"os"
	"strings"
	"text/template"

	"golang.org/x/tools/go/packages"
)

const (
	KindBasic         = "basic"
	KindSlice         = "slice"
	KindMap           = "map"
	KindResetter      = "resetter"
	KindPointer       = "pointer"
	KindUnknown       = "unknown"
	KindStructNoReset = "noreset"
)

type templatePackage struct {
	Package string
	Structs []templateStruct
}

type templateStruct struct {
	Name   string
	Fields []templateField
}

type templateField struct {
	Name  string
	Kind  string
	Value string
}

const templateStr = `
// Code generated by go generate; DO NOT EDIT.
// This file was generated by reset

package {{.Package}}

{{range .Structs}}
func (rs *{{.Name}}) Reset() {
	if rs == nil {
		return
	}

{{range .Fields}}
{{ if eq .Kind "basic"}}rs.{{.Name}} = {{.Value}}{{end -}}
{{ if eq .Kind "slice"}}rs.{{.Name}} = rs.{{.Name}}[:0]{{end -}}
{{ if eq .Kind "map"}}clear(rs.{{.Name}}){{end -}}
{{ if eq .Kind "pointer"}}if rs.{{.Name}} != nil { *rs.{{.Name}} = {{.Value}} }{{end -}}
{{ if eq .Kind "resetter"}}if rs.{{.Name}} != nil { rs.{{.Name}}.Reset() }{{end -}}
{{end}}
}
{{end}}
`

var tmpl = template.Must(template.New("enum").Parse(templateStr))

func main() {
	cfg := &packages.Config{Mode: packages.NeedTypes | packages.NeedName | packages.NeedSyntax | packages.NeedTypesInfo, Dir: "."}
	pkgs, _ := packages.Load(cfg, "./...")

	for _, pkg := range pkgs {
		var finalPackage = templatePackage{Package: pkg.Name}
		for _, file := range pkg.Syntax {
			ast.Inspect(file, func(n ast.Node) bool {
				decl, ok := n.(*ast.GenDecl)
				if !ok || decl.Tok != token.TYPE {
					return true
				}
				ok = strings.Contains(decl.Doc.Text(), "generate:reset")
				if !ok {
					return true
				}

				// итерируемся по всем структурам в блоке
				for _, s := range decl.Specs {
					ts := s.(*ast.TypeSpec)
					st, ok := ts.Type.(*ast.StructType)
					if !ok {
						// не структура: interface, map[...]... и т.п.
						continue
					}
					fields := make([]templateField, 0, len(st.Fields.List))
					for _, field := range st.Fields.List {
						t := pkg.TypesInfo.TypeOf(field.Type)
						for _, name := range field.Names {
							kind, literal := classify(t, pkg)
							fields = append(fields, templateField{Name: name.Name, Kind: kind, Value: literal})
						}

					}
					finalPackage.Structs = append(finalPackage.Structs, templateStruct{Name: ts.Name.Name, Fields: fields})
				}
				return true
			})
		}
		// генерируем код по шаблону
		var buf bytes.Buffer
		if len(finalPackage.Structs) > 0 {
			err := tmpl.Execute(&buf, finalPackage)
			if err != nil {
				log.Fatal(err)
			}
			// форматируем код
			bufFmt, err := format.Source(buf.Bytes())
			if err != nil {
				log.Fatal(err)
			}

			// записываем сгенерированный код в файл
			err = os.WriteFile(fmt.Sprintf("%s/reset.gen.go", pkg.Dir), bufFmt, 0644)
			if err != nil {
				log.Fatal(err)
			}
		}
	}
}

func classify(t types.Type, pkg *packages.Package) (string, string) {
	named, ok := t.(*types.Named)
	if ok {
		obj, _, _ := types.LookupFieldOrMethod(t, true, pkg.Types, "Reset")
		fn, ok := obj.(*types.Func)
		if ok && fn != nil {
			return KindResetter, ""
		}
		return classify(named.Underlying(), pkg)
	}

	switch u := t.Underlying().(type) {
	case *types.Basic:
		switch {
		case u.Info()&types.IsString != 0:
			return KindBasic, "\"\""
		case u.Info()&types.IsBoolean != 0:
			return KindBasic, "false"
		case u.Info()&types.IsInteger != 0:
			return KindBasic, "0"
		case u.Info()&types.IsFloat != 0:
			return KindBasic, "0"
		case u.Info()&types.IsComplex != 0:
			return KindBasic, "0"
		default:
			return KindUnknown, ""
		}

	case *types.Slice:
		return KindSlice, ""
	case *types.Map:
		return KindMap, ""
	case *types.Pointer:
		elem := u.Elem()
		obj, _, _ := types.LookupFieldOrMethod(elem, true, pkg.Types, "Reset")
		fn, ok := obj.(*types.Func)
		if ok && fn != nil {
			return KindResetter, ""
		}
		kind, literal := classify(elem, pkg)
		if kind == KindStructNoReset {
			return KindStructNoReset, ""
		}
		return KindPointer, literal
	case *types.Struct:
		// анонимная структура без Reset
		return KindStructNoReset, ""
	default:
		return KindUnknown, ""
	}
}
